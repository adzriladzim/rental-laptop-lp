// Deep-require string types so EN (English literals) is assignable to ID.
type DeepString<T> = { [K in keyof T]: T[K] extends string ? string : DeepString<T[K]> }

export type Translation = DeepString<(typeof translations)['id']>

export const translationsDict: Record<Locale, Translation> = translations

const STORAGE_KEY = 'sewaintop-locale'

export function detectLocale(): Locale {
  if (typeof window === 'undefined') return 'id'
  const stored = window.localStorage.getItem(STORAGE_KEY)
  if (stored === 'en' || stored === 'id') return stored
  const nav = window.navigator.language?.toLowerCase() ?? ''
  return nav.startsWith('en') ? 'en' : 'id'
}

export function persistLocale(locale: Locale): void {
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEY, locale)
  }
}

export function t(locale: Locale): Translation {
  return translationsDict[locale]
}
